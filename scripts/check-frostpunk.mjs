import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import ts from 'typescript';
const dir=path.resolve('.checks/frostpunk');
fs.mkdirSync(dir,{recursive:true});
fs.writeFileSync(path.join(dir,'package.json'),'{"type":"commonjs"}');
for(const file of ['frostpunk-data','frostpunk-state'])fs.writeFileSync(path.join(dir,`${file}.js`),ts.transpileModule(fs.readFileSync(`lib/${file}.ts`,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText);
fs.copyFileSync('lib/frostpunk-steam.json',path.join(dir,'frostpunk-steam.json'));
const require=createRequire(import.meta.url),d=require(path.join(dir,'frostpunk-data.js')),m=require(path.join(dir,'frostpunk-state.js'));
assert.equal(d.achievements.length,115);
for(const list of [d.achievements,d.stages,d.steps])assert.equal(new Set(list.map(x=>x.id)).size,list.length);
for(const a of d.achievements){assert(d.scenarios[a.scenario]);for(const locale of ['ru','uk','en'])assert(a.name[locale]?.trim());}
for(const step of d.steps){for(const goal of step.goals)assert(d.achievements.some(a=>a.id===goal));for(const stage of step.stages)assert(d.stages.some(s=>s.id===stage));}
let state=m.freshState();
assert.deepEqual(m.parseState(JSON.parse(JSON.stringify(state))),state);
for(const invalid of [{...state,game:'valhalla'},{...state,version:2},{...state,earned:['invented']},{...state,active:'missing'},{...state,runs:[state.runs[0],state.runs[0]]},{...state,runs:[{...state.runs[0],completedSteps:['leader']}]}])assert.throws(()=>m.parseState(invalid));
state=m.changeRun(state,{completedStages:['settlement'],completedSteps:['scout-rescues'],notes:'Before the storm'});
assert.deepEqual(state.earned,[]);
state.snapshots.push({id:'checkpoint',name:'Before',run:structuredClone(m.activeRun(state))});
state.earned.push('leader');
state=m.changeRun(state,{notes:'After',stage:'storm',deaths:true});
state.runs.push(m.freshRun('second','02'));state.active='second';
assert.deepEqual(m.activeRun(state).completedSteps,[]);
state=m.restore(state,'checkpoint');
assert.equal(state.active,'initial');assert.equal(m.activeRun(state).notes,'Before the storm');assert.equal(m.activeRun(state).deaths,false);assert.deepEqual(state.earned,['leader']);
const get=id=>d.achievements.find(a=>a.id===id),run=m.activeRun(state);
assert.equal(m.availability(get('the-saviour'),{...run,deaths:true}),'blocked');
assert.equal(m.availability(get('carnivore'),{...run,food:'mixed'}),'blocked');
assert.equal(m.availability(get('vegetarian'),{...run,food:'hunters'}),'blocked');
assert.equal(m.availability(get('builder'),run),'other');
assert.equal(m.availability(get('new-home-survivor'),run),'other');
assert.equal(m.availability(get('new-home-survivor'),{...run,difficulty:'survivor'}),'now');
assert.equal(m.availability(get('marathon-hard'),{...run,stage:'endless',mode:'serenity',difficulty:'hard'}),'other');
assert.equal(m.availability(get('marathon-hard'),{...run,stage:'endless',mode:'endurance',difficulty:'hard'}),'now');
assert.equal(m.availability(get('banksy'),run),'unknown');
assert.deepEqual(m.parseState(JSON.parse(JSON.stringify(state))),state);
console.log('Frostpunk: 115 catalogue records, separate progress layers, independent runs, safe import, checkpoint restore and scenario restrictions passed.');
